export function findCuratedMatch(rawTopic: string): CuratedEntry | null {
  const lower = rawTopic.toLowerCase().trim();
  const words = lower.split(/[^a-z0-9]+/);

  for (const entry of CURATED_ARCHIVE) {
    const hasMatch = entry.keywords.some((kw) => {
      if (lower.includes(kw)) return true;
      return words.some((w) => w.startsWith(kw) || kw.startsWith(w));
    });
    if (hasMatch) {
      return entry;
    }
  }

  return null;
}
